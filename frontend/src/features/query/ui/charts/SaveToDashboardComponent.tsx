import { LoadingOutlined } from '@ant-design/icons';
import { App, Button, Input, Popover, Select, Spin } from 'antd';
import React, { useState } from 'react';

import { type Dashboard, type Panel, dashboardApi } from '../../../../entity/dashboards';

interface Props {
  projectId: string;
  /** The panel to add, without its id and place. */
  panel: Omit<Panel, 'id' | 'gridPos'>;
  /** "time series", "top values"... */
  typeName: string;
  disabled?: boolean;
  disabledReason?: string;
  /** What the panel keeps; defaults to the search chart's wording. */
  hint?: string;
}

const NEW_DASHBOARD = '__new__';

// Panels go below the tab's last one; time series and tables get the full width.
const nextGridPos = (panels: Panel[], wide: boolean) => ({
  x: 0,
  y: panels.reduce((bottom, p) => Math.max(bottom, p.gridPos.y + p.gridPos.h), 0),
  w: wide ? 12 : 6,
  h: 8,
});

/** "Save to dashboard": adds the chart as a panel to an existing or new dashboard. */
export const SaveToDashboardComponent = ({
  projectId,
  panel,
  typeName,
  disabled,
  disabledReason,
  hint,
}: Props): React.JSX.Element => {
  const { message } = App.useApp();
  const [open, setOpen] = useState(false);
  const [title, setTitle] = useState(panel.title);
  const [dashboards, setDashboards] = useState<Dashboard[] | null>(null);
  const [target, setTarget] = useState<string | undefined>();
  const [newTitle, setNewTitle] = useState('');
  const [isSaving, setIsSaving] = useState(false);

  const openForm = async () => {
    setTitle(panel.title);
    setOpen(true);
    try {
      const response = await dashboardApi.list(projectId);
      const editable = response.dashboards.filter((d) => !d.isAutoGenerated);
      setDashboards(editable);
      setTarget((current) => current ?? editable[0]?.id ?? NEW_DASHBOARD);
    } catch (e: unknown) {
      setDashboards([]);
      setTarget(NEW_DASHBOARD);
      message.error(e instanceof Error ? e.message : 'Failed to load dashboards');
    }
  };

  const save = async () => {
    if (!title.trim()) {
      message.error('Panel title is required');
      return;
    }
    if (target === NEW_DASHBOARD && !newTitle.trim()) {
      message.error('Name the new dashboard');
      return;
    }
    const wide = panel.type === 'line' || panel.type === 'table';
    setIsSaving(true);
    try {
      let dashboardTitle: string;
      if (!target || target === NEW_DASHBOARD) {
        const created = await dashboardApi.create(projectId, {
          title: newTitle.trim(),
          tabs: [
            {
              id: crypto.randomUUID(),
              title: 'Default',
              panels: [
                {
                  ...panel,
                  title: title.trim(),
                  id: crypto.randomUUID(),
                  gridPos: nextGridPos([], wide),
                },
              ],
            },
          ],
        });
        dashboardTitle = created.title;
      } else {
        const dashboard = await dashboardApi.get(projectId, target);
        const [first, ...rest] = dashboard.tabs;
        const tab = first ?? { id: crypto.randomUUID(), title: 'Default', panels: [] };
        const added: Panel = {
          ...panel,
          title: title.trim(),
          id: crypto.randomUUID(),
          gridPos: nextGridPos(tab.panels, wide),
        };
        await dashboardApi.update(projectId, dashboard.id, {
          title: dashboard.title,
          description: dashboard.description,
          tabs: [{ ...tab, panels: [...tab.panels, added] }, ...rest],
          variables: dashboard.variables,
        });
        dashboardTitle = dashboard.title;
      }
      message.success(`Panel "${title.trim()}" added to ${dashboardTitle}`);
      setOpen(false);
    } catch (e: unknown) {
      message.error(e instanceof Error ? e.message : 'Failed to save the panel');
    } finally {
      setIsSaving(false);
    }
  };

  const form = (
    <div role="dialog" aria-label="Save to dashboard" className="flex w-[320px] flex-col gap-3">
      <strong className="font-semibold text-gray-900 dark:text-gray-50">Save to dashboard</strong>
      <label className="flex flex-col gap-1 text-xs text-gray-500 dark:text-gray-400">
        Panel title
        <Input value={title} onChange={(e) => setTitle(e.target.value)} />
      </label>
      <label className="flex flex-col gap-1 text-xs text-gray-500 dark:text-gray-400">
        Dashboard
        {dashboards === null ? (
          <Spin indicator={<LoadingOutlined spin />} size="small" />
        ) : (
          <Select
            value={target}
            onChange={setTarget}
            showSearch
            optionFilterProp="label"
            options={[
              ...dashboards.map((d) => ({ value: d.id, label: d.title })),
              { value: NEW_DASHBOARD, label: 'New dashboard…' },
            ]}
          />
        )}
      </label>
      {target === NEW_DASHBOARD && (
        <label className="flex flex-col gap-1 text-xs text-gray-500 dark:text-gray-400">
          New dashboard name
          <Input value={newTitle} onChange={(e) => setNewTitle(e.target.value)} />
        </label>
      )}
      <span className="text-xs text-gray-500 dark:text-gray-400">
        {hint ??
          `Saved as a ${typeName} panel with this search, split and measure. It follows the dashboard's time range.`}
      </span>
      <span className="flex justify-end gap-2">
        <Button size="small" onClick={() => setOpen(false)}>
          Cancel
        </Button>
        <Button size="small" type="primary" loading={isSaving} onClick={save}>
          Save panel
        </Button>
      </span>
    </div>
  );

  return (
    <Popover
      open={open}
      onOpenChange={(next) => (next ? void openForm() : setOpen(false))}
      trigger="click"
      placement="bottomRight"
      content={form}
      destroyOnHidden
    >
      <Button disabled={disabled} title={disabled ? disabledReason : undefined}>
        Save to dashboard
      </Button>
    </Popover>
  );
};
