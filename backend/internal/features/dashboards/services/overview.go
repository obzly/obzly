const maxMetricOverviewPanels = 6

// metricOverviewPanels graphs the first maxMetricOverviewPanels metric names:
// counters as rate(), others as avg(). "_bucket" series are skipped: a raw
// bucket count means nothing without grouping by le.
func (s *DashboardService) metricOverviewPanels(projectID uuid.UUID) dashboards_models.Panels {
	ctx, cancel := context.WithTimeout(context.Background(), metricOverviewQueryTimeout)
	defer cancel()
	response, err := metrics_core.GetMetricCoreRepository().ListMetricNames(ctx, projectID, nil)
	if err != nil || len(response.Metrics) == 0 {
		return nil
	}

	names := make([]metrics_core.MetricNameInfo, 0, len(response.Metrics))
	for _, m := range response.Metrics {
		if strings.HasSuffix(m.Name, "_bucket") {
			continue
		}
		names = append(names, m)
	}
	sort.Slice(names, func(i, j int) bool { return names[i].Name < names[j].Name })
	if len(names) > maxMetricOverviewPanels {
		names = names[:maxMetricOverviewPanels]
	}

	panels := make(dashboards_models.Panels, len(names))
	for i, m := range names {
		query, title := metricOverviewQuery(m)
		panels[i] = dashboards_models.Panel{
			ID:        uuid.NewString(),
			Title:     title,
			Type:      dashboards_models.PanelTypeLine,
			Source:    dashboards_models.PanelSourceMetrics,
			PromQuery: query,
			GridPos:   dashboards_models.GridPos{X: (i % 2) * 6, Y: 32 + (i/2)*8, W: 6, H: 8},
		}
	}
	return panels
}

func metricOverviewQuery(m metrics_core.MetricNameInfo) (query, title string) {
	selector := promMetricSelector(m.Name)
	if m.Type == metrics_core.MetricTypeCounter {
		return fmt.Sprintf("sum(rate(%s[5m]))", selector), m.Name + " (rate)"
	}
	return fmt.Sprintf("avg(%s)", selector), m.Name + " (avg)"
}

// promMetricSelector uses a legacy-valid name bare and quotes anything else
// (dotted OTel names fail to parse bare). Matches dashboardTemplates.ts.
func promMetricSelector(name string) string {
	if model.LegacyValidation.IsValidMetricName(name) {
		return name
	}
	return fmt.Sprintf(`{"__name__"=%s}`, strconv.Quote(name))
}

// errorLevelsQuery matches ERROR and FATAL logs.
func errorLevelsQuery() *logs_core.QueryNode {
	return &logs_core.QueryNode{
		Type: logs_core.QueryNodeTypeCondition,
		Condition: &logs_core.ConditionNode{
			Field:    "level",
			Operator: logs_core.ConditionOperatorIn,
			Value:    []string{string(logs_core.LogLevelError), string(logs_core.LogLevelFatal)},
		},
	}
}

