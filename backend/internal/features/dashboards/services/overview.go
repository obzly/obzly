// metricOverviewQueryTimeout bounds ListMetricNames here: there is no request
// deadline to inherit.
const metricOverviewQueryTimeout = 30 * time.Second

const (
	overviewTitle       = "Overview"
	overviewDescription = "Auto-generated from your project's log data. Regenerate any time " +
		"to pick up fields you've started sending since — or edit it like any other dashboard."
)

// GenerateOverview builds, or replaces in place, the project's auto-generated
// Overview dashboard: fixed log panels, plus span and metric panels when the
// project has that data.
func (s *DashboardService) GenerateOverview(
	projectID uuid.UUID,
	user *users_models.User,
) (*dashboards_models.Dashboard, error) {
	if err := s.requireWriteAccess(projectID, user); err != nil {
		return nil, err
	}

	panels := overviewPanels()
	if s.projectHasSpans(projectID) {
		panels = append(panels, spanOverviewPanels()...)
	}
	if metricPanels := s.metricOverviewPanels(projectID); len(metricPanels) > 0 {
		panels = append(panels, metricPanels...)
	}

	overviewTab := dashboards_models.Tab{Title: "Overview", Panels: panels}

	existing, err := s.dashboardRepository.GetAutoGeneratedForProject(projectID)
	switch {
	case err == nil:
		// Replace the content but keep the tab ID, so the frontend's selected
		// tab survives.
		if len(existing.Tabs) > 0 {
			overviewTab.ID = existing.Tabs[0].ID
		} else {
			overviewTab.ID = uuid.New().String()
		}
		existing.Tabs = dashboards_models.Tabs{overviewTab}
		existing.Title = overviewTitle
		existing.Description = overviewDescription
		if err := s.dashboardRepository.Update(existing); err != nil {
			return nil, fmt.Errorf("failed to update overview dashboard: %w", err)
		}
		return existing, nil

	case errors.Is(err, gorm.ErrRecordNotFound):
		overviewTab.ID = uuid.New().String()
		dashboard := &dashboards_models.Dashboard{
			ID:              uuid.New(),
			ProjectID:       projectID,
			Title:           overviewTitle,
			Description:     overviewDescription,
			Tabs:            dashboards_models.Tabs{overviewTab},
			IsAutoGenerated: true,
			CreatedBy:       &user.ID,
		}
		if err := s.dashboardRepository.Create(dashboard); err != nil {
			return nil, fmt.Errorf("failed to create overview dashboard: %w", err)
		}
		return dashboard, nil

	default:
		return nil, fmt.Errorf("failed to check for an existing overview dashboard: %w", err)
	}
}

// projectHasSpans treats an error as "no spans": a span storage failure
// shouldn't block the log panels.
func (s *DashboardService) projectHasSpans(projectID uuid.UUID) bool {
	response, err := spans_core.GetSpanCoreRepository().ListServices(projectID, nil)
	if err != nil {
		return false
	}
	return len(response.Services) > 0
}

