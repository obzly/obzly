func Test_CreateDashboard_WithValidPanels_DashboardCreatedAndPanelsGetIDs(t *testing.T) {
	router := CreateDashboardTestRouter()
	owner := users_testing.CreateTestUser(users_enums.UserRoleMember)
	project, _ := projects_testing.CreateTestProjectWithToken("CRUD Create", owner.Token, router)

	request := dashboards_dto.CreateDashboardRequestDTO{
		Title: "My Dashboard",
		Tabs:  []dashboards_models.Tab{{Title: "Default", Panels: []dashboards_models.Panel{samplePanel()}}},
	}

	var response dashboards_models.Dashboard
	test_utils.MakePostRequestAndUnmarshal(
		t, router,
		fmt.Sprintf("/api/v1/projects/dashboards/%s", project.ID.String()),
		"Bearer "+owner.Token, request, http.StatusOK, &response,
	)

	assert.Equal(t, "My Dashboard", response.Title)
	assert.Equal(t, project.ID, response.ProjectID)
	require.Len(t, response.Tabs, 1)
	require.Len(t, response.Tabs[0].Panels, 1)
	assert.NotEmpty(t, response.Tabs[0].Panels[0].ID)
	assert.False(t, response.IsAutoGenerated)
}

