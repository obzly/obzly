// The panel cap per tab alone left a dashboard unbounded; tab count and total
// panels are capped too.
func Test_CreateDashboard_WithTooManyTabs_ReturnsBadRequest(t *testing.T) {
	router := CreateDashboardTestRouter()
	owner := users_testing.CreateTestUser(users_enums.UserRoleMember)
	project, _ := projects_testing.CreateTestProjectWithToken("CRUD Too Many Tabs", owner.Token, router)

	tabs := make([]dashboards_models.Tab, 51)
	for i := range tabs {
		tabs[i] = dashboards_models.Tab{Title: fmt.Sprintf("Tab %d", i)}
	}

	resp := test_utils.MakePostRequest(
		t, router,
		fmt.Sprintf("/api/v1/projects/dashboards/%s", project.ID.String()),
		"Bearer "+owner.Token,
		dashboards_dto.CreateDashboardRequestDTO{Title: "Too Many Tabs", Tabs: tabs},
		http.StatusBadRequest,
	)
	assert.Contains(t, string(resp.Body), "more than 50 tabs")
}

func Test_CreateDashboard_WithTooManyPanelsAcrossTabs_ReturnsBadRequest(t *testing.T) {
	router := CreateDashboardTestRouter()
	owner := users_testing.CreateTestUser(users_enums.UserRoleMember)
	project, _ := projects_testing.CreateTestProjectWithToken("CRUD Too Many Panels", owner.Token, router)

	// 6 tabs x 100 panels: each tab within its cap, 600 over the total of 500.
	tabs := make([]dashboards_models.Tab, 6)
	for i := range tabs {
		panels := make([]dashboards_models.Panel, 100)
		for j := range panels {
			panels[j] = samplePanel()
		}
		tabs[i] = dashboards_models.Tab{Title: fmt.Sprintf("Tab %d", i), Panels: panels}
	}

	resp := test_utils.MakePostRequest(
		t, router,
		fmt.Sprintf("/api/v1/projects/dashboards/%s", project.ID.String()),
		"Bearer "+owner.Token,
		dashboards_dto.CreateDashboardRequestDTO{Title: "Too Many Panels", Tabs: tabs},
		http.StatusBadRequest,
	)
	assert.Contains(t, string(resp.Body), "more than 500 panels")
}

func Test_CreateDashboard_OversizedVariablesOrText_ReturnsBadRequest(t *testing.T) {
	router := CreateDashboardTestRouter()
	owner := users_testing.CreateTestUser(users_enums.UserRoleMember)
	project, _ := projects_testing.CreateTestProjectWithToken("CRUD Oversized", owner.Token, router)
	url := fmt.Sprintf("/api/v1/projects/dashboards/%s", project.ID.String())
	static := func(key string, values []string) dashboards_models.Variable {
		return dashboards_models.Variable{
			Key:          key,
			Source:       dashboards_models.VariableSourceStatic,
			StaticValues: values,
		}
	}

	tooManyVariables := make([]dashboards_models.Variable, 51)
	for i := range tooManyVariables {
		tooManyVariables[i] = static(fmt.Sprintf("v%d", i), []string{"a"})
	}
	tooManyValues := make([]string, 1001)
	for i := range tooManyValues {
		tooManyValues[i] = fmt.Sprintf("value-%d", i)
	}
	longQueryPanel := samplePanel()
	longQueryPanel.Source = dashboards_models.PanelSourceMetrics
	longQueryPanel.PromQuery = strings.Repeat("x", 64<<10+1)

	for name, tc := range map[string]struct {
		request dashboards_dto.CreateDashboardRequestDTO
		message string
	}{
		"variables": {dashboards_dto.CreateDashboardRequestDTO{Title: "x", Variables: tooManyVariables},
			"more than 50 variables"},
		"static values": {dashboards_dto.CreateDashboardRequestDTO{Title: "x",
			Variables: []dashboards_models.Variable{static("env", tooManyValues)}}, "at most 1000 static values"},
		"value size": {dashboards_dto.CreateDashboardRequestDTO{Title: "x",
			Variables: []dashboards_models.Variable{static("env", []string{strings.Repeat("x", 64<<10+1)})}},
			"can't be longer"},
		"description": {dashboards_dto.CreateDashboardRequestDTO{Title: "x",
			Description: strings.Repeat("x", 64<<10+1)}, "description can't be longer"},
		"panel query": {dashboards_dto.CreateDashboardRequestDTO{Title: "x",
			Tabs: []dashboards_models.Tab{{Title: "t", Panels: []dashboards_models.Panel{longQueryPanel}}}},
			"panel query can't be longer"},
	} {
		resp := test_utils.MakePostRequest(t, router, url, "Bearer "+owner.Token, tc.request, http.StatusBadRequest)
		assert.Contains(t, string(resp.Body), tc.message, name)
	}
}

