func Test_UpdateDashboard_ChangesTitleAndPanels(t *testing.T) {
	router := CreateDashboardTestRouter()
	owner := users_testing.CreateTestUser(users_enums.UserRoleMember)
	project, _ := projects_testing.CreateTestProjectWithToken("CRUD Update", owner.Token, router)

	var created dashboards_models.Dashboard
	test_utils.MakePostRequestAndUnmarshal(
		t, router,
		fmt.Sprintf("/api/v1/projects/dashboards/%s", project.ID.String()),
		"Bearer "+owner.Token,
		dashboards_dto.CreateDashboardRequestDTO{Title: "Original"},
		http.StatusOK, &created,
	)

	updateRequest := dashboards_dto.UpdateDashboardRequestDTO{
		Title: "Renamed",
		Tabs: []dashboards_models.Tab{
			{Title: "Default", Panels: []dashboards_models.Panel{samplePanel(), samplePanel()}},
		},
	}
	var updated dashboards_models.Dashboard
	test_utils.MakePutRequestAndUnmarshal(
		t, router,
		fmt.Sprintf("/api/v1/projects/dashboards/%s/%s", project.ID.String(), created.ID.String()),
		"Bearer "+owner.Token, updateRequest, http.StatusOK, &updated,
	)

	assert.Equal(t, "Renamed", updated.Title)
	require.Len(t, updated.Tabs, 1)
	assert.Len(t, updated.Tabs[0].Panels, 2)
	assert.Equal(t, created.ID, updated.ID)
}

