func Test_ImportDashboard_GrafanaFormat_MapsTitleTypeAndLayout(t *testing.T) {
	router := CreateDashboardTestRouter()
	owner := users_testing.CreateTestUser(users_enums.UserRoleMember)
	project, _ := projects_testing.CreateTestProjectWithToken("Import Grafana", owner.Token, router)

	grafanaJSON, err := json.Marshal(map[string]any{
		"title": "My Grafana Dashboard",
		"panels": []map[string]any{
			{
				"title":   "Requests",
				"type":    "timeseries",
				"gridPos": map[string]any{"x": 0, "y": 0, "w": 12, "h": 8},
			},
			{
				"title": "Section header",
				"type":  "row",
			},
			{
				"title":   "Errors",
				"type":    "piechart",
				"gridPos": map[string]any{"x": 0, "y": 8, "w": 6, "h": 8},
			},
		},
	})
	require.NoError(t, err)

	request := dashboards_dto.ImportDashboardRequestDTO{Format: "grafana", JSON: string(grafanaJSON)}

	var response dashboards_dto.ImportDashboardResponseDTO
	test_utils.MakePostRequestAndUnmarshal(
		t, router,
		fmt.Sprintf("/api/v1/projects/dashboards/%s/import", project.ID.String()),
		"Bearer "+owner.Token, request, http.StatusOK, &response,
	)

	require.NotNil(t, response.Dashboard)
	assert.Equal(t, "My Grafana Dashboard", response.Dashboard.Title)
	// The "row" panel is a layout divider, not a chart - only 2 real panels.
	require.Len(t, response.Dashboard.Tabs, 1)
	panels := response.Dashboard.Tabs[0].Panels
	require.Len(t, panels, 2)
	assert.Equal(t, "Requests", panels[0].Title)
	assert.Equal(t, dashboards_models.PanelTypeLine, panels[0].Type)
	assert.Equal(t, 12, panels[0].GridPos.W)
	assert.Equal(t, dashboards_models.PanelTypePie, panels[1].Type)
	assert.NotEmpty(t, response.Warnings)
}

