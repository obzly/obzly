// Package dashboards_models holds the Dashboards storage model. Panels live
// in JSONB rather than a child table: they are never queried server-side and
// a dashboard is read and written as one document.
package dashboards_models

import (
	"database/sql/driver"
	"encoding/json"
	"fmt"
	"time"

	logs_core "obzly/internal/features/logs/core"

	"github.com/google/uuid"
)

type Dashboard struct {
	ID          uuid.UUID `json:"id"          gorm:"column:id"`
	ProjectID   uuid.UUID `json:"projectId"   gorm:"column:project_id"`
	Title       string    `json:"title"       gorm:"column:title"`
	Description string    `json:"description" gorm:"column:description"`
	// Tabs holds every panel; a dashboard always has at least one tab (see
	// dashboards_services.normalizeTabs).
	Tabs Tabs `json:"tabs" gorm:"column:tabs;type:jsonb"`
	// Variables are substituted as ${key} into panel queries by the
	// frontend; the backend only stores them.
	Variables Variables `json:"variables" gorm:"column:variables;type:jsonb"`
	// IsAutoGenerated marks the project's one Overview dashboard, so
	// regeneration knows which row to replace.
	IsAutoGenerated bool `json:"isAutoGenerated" gorm:"column:is_auto_generated"`
	// IsPinned sorts a dashboard to the top of the list; it is shared by the
	// project, not per user.
	IsPinned bool `json:"isPinned" gorm:"column:is_pinned"`
	// FolderID is nil for unfiled; deleting a folder un-files its dashboards
	// (ON DELETE SET NULL) rather than deleting them.
	FolderID  *uuid.UUID `json:"folderId,omitempty"  gorm:"column:folder_id"`
	CreatedBy *uuid.UUID `json:"createdBy,omitempty" gorm:"column:created_by"`
	CreatedAt time.Time  `json:"createdAt"           gorm:"column:created_at"`
	UpdatedAt time.Time  `json:"updatedAt"           gorm:"column:updated_at"`
}

func (Dashboard) TableName() string {
	return "dashboards"
}

// Folder groups a project's dashboards for navigation only; it carries no
// permissions.
type Folder struct {
	ID        uuid.UUID `json:"id"        gorm:"column:id"`
	ProjectID uuid.UUID `json:"projectId" gorm:"column:project_id"`
	Title     string    `json:"title"     gorm:"column:title"`
	CreatedAt time.Time `json:"createdAt" gorm:"column:created_at"`
	UpdatedAt time.Time `json:"updatedAt" gorm:"column:updated_at"`
}

func (Folder) TableName() string {
	return "dashboard_folders"
}

type PanelType string

const (
	PanelTypeLine  PanelType = "line"
	PanelTypeBar   PanelType = "bar"
	PanelTypePie   PanelType = "pie"
	PanelTypeStat  PanelType = "stat"
	PanelTypeTable PanelType = "table"
)

func (t PanelType) IsValid() bool {
	switch t {
	case PanelTypeLine, PanelTypeBar, PanelTypePie, PanelTypeStat, PanelTypeTable:
		return true
	default:
		return false
	}
}

// GridPos is a panel's position and size in grid units (12 columns wide).
type GridPos struct {
	X int `json:"x"`
	Y int `json:"y"`
	W int `json:"w"`
	H int `json:"h"`
}

// PanelSource picks which signal a panel queries.
type PanelSource string

const (
	PanelSourceLogs    PanelSource = "logs"
	PanelSourceSpans   PanelSource = "spans"
	PanelSourceMetrics PanelSource = "metrics"
)

// IsValid also accepts "": panels stored before Source existed mean "logs"
// (see EffectiveSource).
func (s PanelSource) IsValid() bool {
	switch s {
	case PanelSourceLogs, PanelSourceSpans, PanelSourceMetrics, "":
		return true
	default:
		return false
	}
}

// PanelUnit is a display hint for a panel's values; it never affects the
// query.
type PanelUnit string

const (
	PanelUnitNone    PanelUnit = ""
	PanelUnitBytes   PanelUnit = "bytes"
	PanelUnitPercent PanelUnit = "percent"
)

// IsValid also accepts "" (no special formatting).
func (u PanelUnit) IsValid() bool {
	switch u {
	case PanelUnitNone, PanelUnitBytes, PanelUnitPercent:
		return true
	default:
		return false
	}
}

// Panel is one chart: a saved query against the signal Source names, plus
// display metadata (see dashboards_services.ExecutePanelQuery).
type Panel struct {
	ID     string      `json:"id"`
	Title  string      `json:"title"`
	Type   PanelType   `json:"type"`
	Source PanelSource `json:"source,omitempty"`

	// Logs-source only.
	Query *logs_core.QueryNode `json:"query,omitempty"`

	// Spans-source only. Metric is a spans_core.AggregationMetric ("" means
	// count), kept a string so this package needn't import spans_core.
	ServiceName   string `json:"serviceName,omitempty"`
	OperationName string `json:"operationName,omitempty"`
	RootSpansOnly bool   `json:"rootSpansOnly,omitempty"`
	Metric        string `json:"metric,omitempty"`

	// Metrics-source only: a PromQL expression, run as a range query over
	// the panel's window.
	PromQuery string `json:"promQuery,omitempty"`

	// GroupField is any log field for a logs panel, a spans_core.GroupField
	// for a spans panel.
	GroupField string    `json:"groupField,omitempty"`
	BucketMs   int64     `json:"bucketMs,omitempty"`
	Limit      int       `json:"limit,omitempty"`
	Unit       PanelUnit `json:"unit,omitempty"`
	GridPos    GridPos   `json:"gridPos"`
}

// VariableSource picks where a variable's selectable values come from.
type VariableSource string

const (
	VariableSourceStatic      VariableSource = "static"
	VariableSourceMetricLabel VariableSource = "metricLabel"
	VariableSourceServices    VariableSource = "services"
)

func (s VariableSource) IsValid() bool {
	switch s {
	case VariableSourceStatic, VariableSourceMetricLabel, VariableSourceServices:
		return true
	default:
		return false
	}
}

// Variable is a dashboard template variable, referenced as ${Key} in panel
// queries.
type Variable struct {
	Key    string         `json:"key"`
	Label  string         `json:"label"`
	Source VariableSource `json:"source"`
	// MetricLabelName is required when Source == metricLabel.
	MetricLabelName string `json:"metricLabelName,omitempty"`
	// StaticValues is required when Source == static.
	StaticValues []string `json:"staticValues,omitempty"`
	DefaultValue string   `json:"defaultValue,omitempty"`
}

// EffectiveSource defaults an unset Source to "logs", what panels stored
// before Source existed always meant.
func (p Panel) EffectiveSource() PanelSource {
	if p.Source == "" {
		return PanelSourceLogs
	}
	return p.Source
}

// Tab is one tab of a dashboard, with its own panel grid.
type Tab struct {
	ID     string `json:"id"`
	Title  string `json:"title"`
	Panels Panels `json:"panels"`
}

// Tabs is stored as one JSONB column (hand-written: GORM has no JSONB
// mapping and gorm.io/datatypes isn't worth a dependency).
type Tabs []Tab

func (t Tabs) Value() (driver.Value, error) {
	if t == nil {
		return "[]", nil
	}
	encoded, err := json.Marshal(t)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal tabs: %w", err)
	}
	return string(encoded), nil
}

func (t *Tabs) Scan(value any) error {
	if value == nil {
		*t = Tabs{}
		return nil
	}

	var raw []byte
	switch typed := value.(type) {
	case []byte:
		raw = typed
	case string:
		raw = []byte(typed)
	default:
		return fmt.Errorf("unsupported type %T for Tabs.Scan", value)
	}

	if len(raw) == 0 {
		*t = Tabs{}
		return nil
	}

	var decoded Tabs
	if err := json.Unmarshal(raw, &decoded); err != nil {
		return fmt.Errorf("failed to unmarshal tabs: %w", err)
	}
	*t = decoded
	return nil
}

