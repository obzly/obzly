package dashboards_repositories

import (
	"time"

	dashboards_models "obzly/internal/features/dashboards/models"
	"obzly/internal/storage"

	"github.com/google/uuid"
)

type DashboardRepository struct{}

func (r *DashboardRepository) Create(dashboard *dashboards_models.Dashboard) error {
	if dashboard.ID == uuid.Nil {
		dashboard.ID = uuid.New()
	}
	now := time.Now().UTC()
	if dashboard.CreatedAt.IsZero() {
		dashboard.CreatedAt = now
	}
	dashboard.UpdatedAt = now

	return storage.GetDb().Create(dashboard).Error
}

func (r *DashboardRepository) GetByID(dashboardID uuid.UUID) (*dashboards_models.Dashboard, error) {
	var dashboard dashboards_models.Dashboard
	if err := storage.GetDb().Where("id = ?", dashboardID).First(&dashboard).Error; err != nil {
		return nil, err
	}
	return &dashboard, nil
}

func (r *DashboardRepository) ListByProject(projectID uuid.UUID) ([]*dashboards_models.Dashboard, error) {
	var dashboards []*dashboards_models.Dashboard
	err := storage.GetDb().
		Where("project_id = ?", projectID).
		Order("is_pinned DESC, is_auto_generated DESC, created_at ASC").
		Find(&dashboards).Error
	return dashboards, err
}

// SetPinned updates one column, not a full Save, so it can't clobber a
// concurrent panel edit.
func (r *DashboardRepository) SetPinned(dashboardID uuid.UUID, pinned bool) error {
	return storage.GetDb().
		Model(&dashboards_models.Dashboard{}).
		Where("id = ?", dashboardID).
		Update("is_pinned", pinned).Error
}

// GetAutoGeneratedForProject finds the project's Overview dashboard, so
// regeneration replaces it in place.
func (r *DashboardRepository) GetAutoGeneratedForProject(projectID uuid.UUID) (*dashboards_models.Dashboard, error) {
	var dashboard dashboards_models.Dashboard
	err := storage.GetDb().
		Where("project_id = ? AND is_auto_generated = TRUE", projectID).
		First(&dashboard).Error
	if err != nil {
		return nil, err
	}
	return &dashboard, nil
}

func (r *DashboardRepository) Update(dashboard *dashboards_models.Dashboard) error {
	dashboard.UpdatedAt = time.Now().UTC()
	return storage.GetDb().Save(dashboard).Error
}

func (r *DashboardRepository) Delete(dashboardID uuid.UUID) error {
	return storage.GetDb().Delete(&dashboards_models.Dashboard{}, dashboardID).Error
}

func (r *DashboardRepository) DeleteAllForProject(projectID uuid.UUID) error {
	return storage.GetDb().Where("project_id = ?", projectID).Delete(&dashboards_models.Dashboard{}).Error
}

// SetFolder moves a dashboard into folderID (nil un-files it); one column,
// like SetPinned.
func (r *DashboardRepository) SetFolder(dashboardID uuid.UUID, folderID *uuid.UUID) error {
	return storage.GetDb().
		Model(&dashboards_models.Dashboard{}).
		Where("id = ?", dashboardID).
		Update("folder_id", folderID).Error
}

type FolderRepository struct{}

